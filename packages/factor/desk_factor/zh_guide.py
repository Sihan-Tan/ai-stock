def zh_guide_for_talib(talib_name: str) -> str:
    """
    返回三段式详述；缺失时回退短中文名。

    @param talib_name: TA-Lib 函数名或 CLOSE 等伪因子名
    """
    key = (talib_name or "").strip()
    if not key:
        return ""
    if key in TALIB_ZH_GUIDE:
        return TALIB_ZH_GUIDE[key]
    return zh_desc_for_talib(key)
